"""Create a ready-to-run GitHub project; exclude account metadata and local inputs."""
import hashlib,json,pathlib,shutil,zipfile
ROOT=pathlib.Path(__file__).resolve().parent
RELEASES=(ROOT/'releases').resolve();RELEASES.mkdir(exist_ok=True)
DEST=RELEASES/'arknights-headhunt';ARCHIVE=RELEASES/'arknights-headhunt-offline.zip'
marker=DEST/'.generated-offline-project'
if DEST.exists():
 if DEST.is_symlink() or DEST.resolve().parent!=RELEASES or not marker.is_file():raise RuntimeError('Refusing to replace an unrecognized output directory')
 shutil.rmtree(DEST)
DEST.mkdir();marker.write_text('Generated by package-project.py. Rebuild from the source project.\n',encoding='utf-8')
files=[]
for directory in ['dist','tests']:
 for path in (ROOT/directory).rglob('*'):
  if path.is_file():
   if path.is_symlink() or not path.resolve().is_relative_to(ROOT):raise RuntimeError('Source path outside project')
   files.append(path)
for path in ROOT.iterdir():
 if path.is_file() and not path.name.endswith('.tmp.json') and (path.suffix in ['.md','.mjs','.py','.json','.html'] or path.name in ['.gitignore','.nojekyll']):files.append(path)
for path in sorted(files):
 relative=path.relative_to(ROOT);target=DEST/relative;target.parent.mkdir(parents=True,exist_ok=True);shutil.copy2(path,target)
(DEST/'打开说明.txt').write_text('请先完整解压全部文件，再双击本目录的 index.html。\n无需 GPT 账号、服务器或安装依赖，可断网使用。\n首次点击页面后才能播放声音，这是浏览器的正常规则。\n保留整个 dist 文件夹；开发和素材出处请看 README.md。\n',encoding='utf-8')
with zipfile.ZipFile(ARCHIVE,'w',compression=zipfile.ZIP_DEFLATED,compresslevel=6) as archive:
 for path in sorted(DEST.rglob('*')):
  if path.is_file():archive.write(path,'arknights-headhunt/'+path.relative_to(DEST).as_posix())
with zipfile.ZipFile(ARCHIVE) as archive:
 assert archive.testzip() is None
 names=archive.namelist()
 assert 'arknights-headhunt/index.html' in names and 'arknights-headhunt/dist/app.bundle.js' in names
 assert not any('/.git/' in n or '/.openai/' in n or '/node_modules/' in n or n.endswith('.mp4') for n in names)
digest=hashlib.sha256(ARCHIVE.read_bytes()).hexdigest()
(RELEASES/'SHA256SUMS.txt').write_text(digest+'  '+ARCHIVE.name+'\n',encoding='utf-8')
print(json.dumps({'project':str(DEST),'archive':str(ARCHIVE),'bytes':ARCHIVE.stat().st_size,'files':len(names),'sha256':digest},ensure_ascii=True))
